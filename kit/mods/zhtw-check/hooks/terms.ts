// Longest first, so 数据库 is one finding, not 数据 plus 库.
export const TERMS: [string, string][] = [...new Map(PAIRS).entries()].sort((a, b) => b[0].length - a[0].length)

export type Finding = { from: string; to: string; count: number }

const CJK = /[㐀-鿿]/

export function scan(text: string): Finding[] {
  if (!CJK.test(text)) return []
  const covered = new Set<number>()
  const found: Finding[] = []
  for (const [from, to] of TERMS) {
    let count = 0
    for (let at = text.indexOf(from); at >= 0; at = text.indexOf(from, at + from.length)) {
      if (covered.has(at)) continue
      count += 1
      for (let i = 0; i < from.length; i++) covered.add(at + i)
    }
    if (count > 0) found.push({ from, to, count })
  }
  const chars = new Map<string, number>()
  for (let i = 0; i < text.length; i++) {
    const c = text[i] ?? ''
    if (SIMPLIFIED.has(c) && !covered.has(i)) chars.set(c, (chars.get(c) ?? 0) + 1)
  }
  if (chars.size > 0) {
    const count = [...chars.values()].reduce((n, k) => n + k, 0)
    found.push({ from: [...chars.keys()].slice(0, 12).join(''), to: '對應的繁體字', count })
  }
  return found
}

export function describe(found: Finding[], max = 6) {
  const shown = found.slice(0, max).map(f => `${f.from}→${f.to}${f.count > 1 ? `（${f.count} 處）` : ''}`)
  return found.length > max ? `${shown.join('、')} 等 ${found.length} 項` : shown.join('、')
}

// Code is not prose: fences and inline code are left out of a reply's check.
export function prose(text: string) {
  return text.replace(/```[\s\S]*?```/g, ' ').replace(/`[^`\n]*`/g, ' ')
}
